        function applyHomepageLanguage() {

            const language =
                localStorage.getItem("aitutorLanguage") || "en";

            const words =
                homepageTranslations[language] ||
                homepageTranslations.en;

            document
                .querySelectorAll("[data-i18n]")
                .forEach(element => {

                    const key =
                        element.getAttribute("data-i18n");

                    if (words[key]) {
                        element.textContent = words[key];
                    }

                });

        }


        document.addEventListener(
            "DOMContentLoaded",
            () => {

                applyHomepageLanguage();

                const languageSelect =
                    document.getElementById("languageSelect");

                if (languageSelect) {

                    languageSelect.addEventListener(
                        "change",
                        () => {

                            setTimeout(
                                applyHomepageLanguage,
                                0
                            );

                        }
                    );

                }

                document.addEventListener(
                    "nachoLanguageChanged",
                    applyHomepageLanguage
                );

            }
        );

    
