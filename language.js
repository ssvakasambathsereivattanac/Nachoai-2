/* =========================
   INITIALIZE
========================= */

function initializeNachoAI() {
    const savedTheme = getTheme();

    document.documentElement.classList.toggle(
        "dark-mode",
        savedTheme === "dark"
    );

    addQuizDarkMode();
    createThemeButton();
    applyLanguage();
    updateThemeButton();

    const languageSelect =
        document.getElementById("languageSelect");

    if (
        languageSelect &&
        !languageSelect.dataset.nachoListener
    ) {
        languageSelect.dataset.nachoListener = "true";

        languageSelect.value = getLanguage();

        languageSelect.addEventListener(
            "change",
            () => {
                setLanguage(
                    languageSelect.value
                );
            }
        );
    }
}


if (document.readyState === "loading") {
    document.addEventListener(
        "DOMContentLoaded",
        initializeNachoAI
    );
} else {
    initializeNachoAI();
}